create or replace function public.revoke_purchase_order(
  p_order_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  order_row public.purchase_orders%rowtype;
  key_row public.exam_keys%rowtype;
begin
  if not private.is_admin() then
    raise exception 'ADMIN_ONLY';
  end if;

  if nullif(trim(p_reason), '') is null then
    raise exception 'REVOCATION_REASON_REQUIRED';
  end if;

  select *
  into order_row
  from public.purchase_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'PURCHASE_ORDER_NOT_FOUND';
  end if;

  select *
  into key_row
  from public.exam_keys
  where source_order_id = p_order_id
  for update;

  if found then
    update public.exam_keys
    set status = 'revoked',
        deleted_at = now(),
        updated_at = now()
    where id = key_row.id;
  end if;

  update public.purchase_orders
  set status = 'refunded',
      failure_code = left(trim(p_reason), 200),
      updated_at = now()
  where id = p_order_id;

  if to_regclass('public.admin_audit_log') is not null then
    insert into public.admin_audit_log (
      actor_user_id,
      action,
      entity_type,
      entity_id,
      details
    ) values (
      (select auth.uid()),
      'refund_revoke',
      'purchase_order',
      p_order_id::text,
      jsonb_build_object('reason', left(trim(p_reason), 500), 'key_id', key_row.id)
    );
  end if;

