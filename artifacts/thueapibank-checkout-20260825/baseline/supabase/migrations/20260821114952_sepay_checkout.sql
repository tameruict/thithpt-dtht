create or replace function private.fulfill_purchase_order(
  p_order_id uuid,
  p_provider_reference text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  order_row public.purchase_orders%rowtype;
  key_row public.exam_keys%rowtype;
  key_id uuid;
  key_code text;
  expiry timestamptz;
  attempt_count integer;
  valid_days integer;
begin
  select *
  into order_row
  from public.purchase_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'PURCHASE_ORDER_NOT_FOUND';
  end if;

  if order_row.status in ('cancelled', 'refunded') then
    raise exception 'PURCHASE_ORDER_NOT_PAYABLE';
  end if;

  attempt_count := greatest((order_row.product_snapshot ->> 'attempt_count')::integer, 1);
  valid_days := nullif(order_row.product_snapshot ->> 'valid_days', '')::integer;
  expiry := case
    when valid_days is null then null
    else now() + make_interval(days => valid_days)
  end;

  select *
  into key_row
  from public.exam_keys
  where source_order_id = p_order_id
  for update;

  if not found then
    insert into public.students (id, full_name)
    select profile.id, profile.full_name
    from public.profiles profile
    where profile.id = order_row.student_id
    on conflict (id) do nothing;

    loop
      key_id := extensions.gen_random_uuid();
      key_code := 'BUY-' || upper(replace(substr(key_id::text, 1, 16), '-', ''));
      begin
        insert into public.exam_keys (
          id,
          code,
          exam_room_id,
          batch_id,
          assigned_to,
          total_attempts,
          used_attempts,
          status,
          expires_at,
          price_paid,
          payment_ref,
          is_public,
          source_order_id
        ) values (
          key_id,
          key_code,
          null,
          null,
          order_row.student_id,
          attempt_count,
          0,
          'unused',
          expiry,
          order_row.amount,
          'sepay:' || coalesce(nullif(trim(p_provider_reference), ''), order_row.payment_code),
          false,
          p_order_id
        );
        exit;
      exception
        when unique_violation then
          key_id := null;
      end;
    end loop;
  else
    key_id := key_row.id;
    key_code := key_row.code;
  end if;

  update public.purchase_orders
  set status = 'fulfilled',
      provider = coalesce(provider, 'sepay'),
      provider_order_ref = coalesce(
        provider_order_ref,
        nullif(trim(p_provider_reference), '')
      ),
      paid_at = coalesce(paid_at, now()),
      fulfilled_at = coalesce(fulfilled_at, now()),
      failure_code = null,
      updated_at = now()
  where id = p_order_id;

  return jsonb_build_object(
    'order_id', p_order_id,
    'status', 'fulfilled',
    'key_id', key_id,
    'key_code', key_code
  );
end;
$$;

revoke all on function private.fulfill_purchase_order(uuid, text)
  from public, anon, authenticated;

create or replace function public.create_purchase_order(
  p_product_id uuid,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  current_student_id uuid := (select auth.uid());
  product_row public.key_products%rowtype;
  existing_order public.purchase_orders%rowtype;
  order_id uuid;
  payment_code text;
begin
  if current_student_id is null
     or not exists (
       select 1
       from public.profiles profile
       where profile.id = current_student_id
         and profile.role = 'student'
     ) then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  if nullif(trim(p_idempotency_key), '') is null
     or length(trim(p_idempotency_key)) > 120 then
    raise exception 'IDEMPOTENCY_KEY_INVALID';
  end if;

  select *
  into existing_order
  from public.purchase_orders
  where purchase_orders.student_id = current_student_id
    and purchase_orders.idempotency_key = trim(p_idempotency_key);

  if found then
    return jsonb_build_object(
      'order_id', existing_order.id,
      'payment_code', existing_order.payment_code,
      'amount', existing_order.amount,
      'currency', existing_order.currency,
      'status', existing_order.status,
      'expires_at', existing_order.expires_at,
      'product_snapshot', existing_order.product_snapshot
    );
  end if;

  select *
  into product_row
  from public.key_products
  where id = p_product_id
    and is_active
    and archived_at is null
  for update;

  if not found then
    raise exception 'PRODUCT_NOT_AVAILABLE';
  end if;

  order_id := extensions.gen_random_uuid();
  payment_code := 'THPT' || upper(replace(substr(order_id::text, 1, 12), '-', ''));

  insert into public.purchase_orders (
    id,
    student_id,
    product_id,
    status,
    amount,
    currency,
    product_snapshot,
    idempotency_key,
    payment_code,
    expires_at
  ) values (
    order_id,
    current_student_id,
    product_row.id,
    'pending',
    product_row.price_amount,
    product_row.currency,
    jsonb_build_object(
      'id', product_row.id,
      'code', product_row.code,
      'name', product_row.name,
      'product_kind', product_row.product_kind,
      'attempt_count', product_row.attempt_count,
      'price_amount', product_row.price_amount,
      'currency', product_row.currency,
      'valid_days', product_row.valid_days
    ),
    trim(p_idempotency_key),
    payment_code,
    now() + interval '24 hours'
  )
  on conflict (idempotency_key) do nothing;

  select *
  into existing_order
  from public.purchase_orders purchase
  where purchase.id = order_id
     or (
       purchase.student_id = current_student_id
       and purchase.idempotency_key = trim(p_idempotency_key)
     );

  if not found then
    raise exception 'PURCHASE_ORDER_CREATE_FAILED';
  end if;

  return jsonb_build_object(
    'order_id', existing_order.id,
    'payment_code', existing_order.payment_code,
    'amount', existing_order.amount,
    'currency', existing_order.currency,
    'status', existing_order.status,
    'expires_at', existing_order.expires_at,
    'product_snapshot', existing_order.product_snapshot
  );
end;
$$;

revoke all on function public.create_purchase_order(uuid, text)
  from public, anon;
grant execute on function public.create_purchase_order(uuid, text)
  to authenticated;

create or replace function public.process_sepay_payment(
  p_provider_event_id text,
  p_payment_code text,
  p_amount integer,
  p_transfer_type text,
  p_account_number text,
  p_expected_account_number text,
  p_provider_reference text,
  p_payload jsonb,
  p_payload_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  order_row public.purchase_orders%rowtype;
  event_row public.payment_events%rowtype;
  result jsonb;
  existing_status text;
  existing_key_code text;
  event_type text;
  processing_error text;
begin
  if coalesce((select auth.jwt() ->> 'role'), '') <> 'service_role' then
    raise exception 'SERVICE_ROLE_ONLY';
  end if;

  if nullif(trim(p_provider_event_id), '') is null then
    raise exception 'PROVIDER_EVENT_ID_REQUIRED';
  end if;

  if p_payload_sha256 !~ '^[0-9a-f]{64}$' then
    raise exception 'PAYLOAD_HASH_INVALID';
  end if;

  select *
  into event_row
  from public.payment_events
  where provider = 'sepay'
    and provider_event_id = trim(p_provider_event_id);

  if found then
    select purchase.status, key.code
    into existing_status, existing_key_code
    from public.purchase_orders purchase
    left join public.exam_keys key on key.source_order_id = purchase.id
    where purchase.id = event_row.order_id;

    return jsonb_build_object(
      'duplicate', true,
      'accepted', event_row.processing_error is null,
      'event_id', event_row.id,
      'order_id', event_row.order_id,
      'status', coalesce(existing_status, 'unmatched'),
      'key_code', existing_key_code
    );
  end if;

  select *
  into order_row
  from public.purchase_orders
  where upper(payment_code) = upper(trim(coalesce(p_payment_code, '')))
  for update;

  if not found then
    insert into public.payment_events (
      provider,
      provider_event_id,
      event_type,
      payload_sha256,
      payload,
      processed_at,
      processing_error
    ) values (
      'sepay',
      trim(p_provider_event_id),
      'unmatched',
      lower(p_payload_sha256),
      coalesce(p_payload, '{}'::jsonb),
      now(),
      'PAYMENT_CODE_NOT_FOUND'
    );

    return jsonb_build_object(
      'duplicate', false,
      'accepted', false,
      'status', 'unmatched',
      'error', 'PAYMENT_CODE_NOT_FOUND'
    );
  end if;

  if lower(trim(coalesce(p_transfer_type, ''))) <> 'in' then
    event_type := 'invalid_transfer';
    processing_error := 'TRANSFER_TYPE_NOT_IN';
  elsif p_amount is null or p_amount <> order_row.amount then
    event_type := 'invalid_amount';
    processing_error := 'PAYMENT_AMOUNT_MISMATCH';
  elsif nullif(trim(coalesce(p_account_number, '')), '') is null
     or nullif(trim(coalesce(p_expected_account_number, '')), '') is null
     or trim(p_account_number) <> trim(p_expected_account_number) then
    event_type := 'invalid_account';
    processing_error := 'PAYMENT_ACCOUNT_MISMATCH';
  else
    event_type := 'payment_received';
    processing_error := null;
  end if;

  if processing_error is not null then
    insert into public.payment_events (
      order_id,
      provider,
      provider_event_id,
      event_type,
      payload_sha256,
      payload,
      received_at,
      processed_at,
      processing_error
    ) values (
      order_row.id,
      'sepay',
      trim(p_provider_event_id),
      event_type,
      lower(p_payload_sha256),
      coalesce(p_payload, '{}'::jsonb),
      now(),
      now(),
      processing_error
    );

    return jsonb_build_object(
      'duplicate', false,
      'accepted', false,
      'status', order_row.status,
      'order_id', order_row.id,
      'error', processing_error
    );
  end if;

  if order_row.expires_at is not null and order_row.expires_at <= now() then
    processing_error := 'PURCHASE_ORDER_EXPIRED';
    insert into public.payment_events (
      order_id,
      provider,
      provider_event_id,
      event_type,
      payload_sha256,
      payload,
      received_at,
      processed_at,
      processing_error
    ) values (
      order_row.id,
      'sepay',
      trim(p_provider_event_id),
      'expired_order',
      lower(p_payload_sha256),
      coalesce(p_payload, '{}'::jsonb),
      now(),
      now(),
      processing_error
    );

    update public.purchase_orders
    set status = 'failed', failed_at = now(), failure_code = processing_error
    where id = order_row.id and status = 'pending';

    return jsonb_build_object(
      'duplicate', false,
      'accepted', false,
      'status', 'failed',
      'order_id', order_row.id,
      'error', processing_error
    );
  end if;

  insert into public.payment_events (
    order_id,
    provider,
    provider_event_id,
    event_type,
    payload_sha256,
    payload,
    received_at,
    processed_at
  ) values (
    order_row.id,
    'sepay',
    trim(p_provider_event_id),
    'payment_received',
    lower(p_payload_sha256),
    coalesce(p_payload, '{}'::jsonb),
    now(),
    now()
  );

  update public.purchase_orders
  set status = case when status = 'pending' then 'paid' else status end,
      provider = 'sepay',
      provider_order_ref = coalesce(
        nullif(trim(p_provider_reference), ''),
        trim(p_provider_event_id)
      ),
      paid_at = coalesce(paid_at, now()),
      updated_at = now()
  where id = order_row.id;

  result := private.fulfill_purchase_order(
    order_row.id,
    coalesce(nullif(trim(p_provider_reference), ''), trim(p_provider_event_id))
  );

  return jsonb_build_object(
    'duplicate', false,
    'accepted', true,
    'event_id', (
      select id
      from public.payment_events
      where provider = 'sepay'
        and provider_event_id = trim(p_provider_event_id)
    )
  ) || result;
end;
$$;

